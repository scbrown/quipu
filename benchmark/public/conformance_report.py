#!/usr/bin/env python3
"""Render the public conformance page and badge endpoints from the pinned ledgers.

The ledgers under ``benchmark/public/results/`` are the only source of truth.
Nothing here re-scores anything: this turns a measured ledger into the two
artifacts a stranger actually reads — a page they can re-derive, and a badge
that cannot flatter us, because both are recomputed from the same JSON.

``--check`` re-renders into memory and compares against what is committed. CI
runs it so the published page cannot drift away from the ledger it claims to
report; a page that says 18/168 while the ledger says 12/168 is worse than no
page at all.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# Ledger file -> (badge slug, human label, the class keys it carries).
# The syntax ledger predates the multi-class evaluation runner and has its own
# shape ("totals", not "classes"); it is normalised into the same view below.
SYNTAX_LEDGER = "sparql11-syntax.json"
EVALUATION_LEDGER = "sparql11-evaluation.json"
ENTAILMENT_LEDGER = "sparql11-entailment.json"
SHACL_LEDGER = "shacl-core.json"
FEDERATED_LEDGER = "sparql11-federated-query.json"
RDF11_SYNTAX_LEDGER = "rdf11-syntax.json"
RDF12_SYNTAX_LEDGER = "rdf12-syntax.json"
RDF_SYNTAX_SUITES = (
    ("rdf-turtle", "Turtle"),
    ("rdf-n-triples", "N-Triples"),
    ("rdf-n-quads", "N-Quads"),
    ("rdf-trig", "TriG"),
)

CLASS_LABELS = {
    "syntax": "query syntax",
    "query-evaluation": "query evaluation",
    "protocol": "protocol",
    "update": "update",
    "entailment": "entailment",
    "result-format": "result format",
    "federated-query": "federated query (`SERVICE`)",
}

# Order the page and the badge set. Syntax first because it is the one class
# that passes in full, and burying it would be as dishonest as leading with it
# and calling it "SPARQL 1.1 conformance".
CLASS_ORDER = [
    "syntax",
    "query-evaluation",
    "federated-query",
    "result-format",
    "protocol",
    "update",
    "entailment",
]

PASS_STATUSES = frozenset({"passed"})
# A test that the harness cannot execute is not a pass and not a failure. It is
# counted, named, and given a reason -- never quietly dropped from the
# denominator, which is the usual way a conformance number gets inflated.
UNSUPPORTED_STATUSES = frozenset({"unsupported"})

GENERATED_HEADER = (
    "<!-- Generated by benchmark/public/conformance_report.py from\n"
    "     benchmark/public/results/*.json. Do not edit by hand: `just conformance-check`\n"
    "     (and CI) will fail if this file and the ledgers disagree. -->\n"
)


class LedgerError(RuntimeError):
    """The ledgers on disk are missing or do not have the expected shape."""


# Other stores measured by benchmark/competitors/competitors.py with the same
# discovery, selection and comparison code. Order is the page order, fixed so a
# re-derive cannot reshuffle the table into a ranking nobody chose.
COMPETITORS = (
    ("rdf4j", "RDF4J"),
    ("oxigraph", "Oxigraph"),
    ("fuseki", "Jena Fuseki"),
    ("rdflib", "rdflib"),
)
COMPETITOR_CLASSES = ("query-evaluation", "update")


def load_competitors(competitors_dir: Path, suite_revision: str) -> list[dict]:
    """The competitor ledgers, refused unless every one ran at quipu's suite revision.

    A row measured against a different rdf-tests commit would sit in the same
    table as quipu's and read as the same test, so a mismatch is an error, not a
    footnote.
    """
    rows = []
    for key, label in COMPETITORS:
        path = competitors_dir / f"{key}.json"
        if not path.is_file():
            raise LedgerError(f"missing competitor ledger: {path}")
        ledger = json.loads(path.read_text())
        if ledger.get("suite_revision") != suite_revision:
            raise LedgerError(
                f"{path} ran at rdf-tests {str(ledger.get('suite_revision'))[:8]}, "
                f"quipu's ledgers at {suite_revision[:8]}; re-run it at the same revision"
            )
        classes = {}
        for name in COMPETITOR_CLASSES:
            counts = ledger.get("classes", {}).get(name)
            if not counts or "cases" not in counts:
                raise LedgerError(f"{path} carries no {name!r} class")
            classes[name] = {
                "passed": counts.get("passed", 0),
                "cases": counts["cases"],
                "lexical_form_only": counts.get("lexical_form_only", 0),
            }
        rows.append({"key": key, "label": label, "version": ledger["system_version"], "classes": classes})
    return rows


def reason_of(row: dict) -> str:
    """Unsupported rows carry ``reason``; executed rows carry ``diagnostic``."""
    return (row.get("reason") or row.get("diagnostic") or "").strip()


def family_of(row: dict) -> str:
    """Feature family = the pinned suite's own directory for the manifest.

    Deriving the grouping from the W3C layout rather than inventing one keeps
    the classification re-derivable by anyone holding the same suite revision,
    and keeps it stable when we fix tests.
    """
    manifest = row.get("manifest", "")
    return manifest.rsplit("/", 1)[0] if "/" in manifest else "(root)"


def tally(rows: list[dict]) -> dict[str, int]:
    counts = {"passed": 0, "failed": 0, "error": 0, "unsupported": 0}
    for row in rows:
        status = row.get("status", "")
        if status not in counts:
            raise LedgerError(f"unknown status {status!r} in ledger row {row.get('id')!r}")
        counts[status] += 1
    counts["cases"] = len(rows)
    counts["executable"] = counts["cases"] - counts["unsupported"]
    return counts


def load_rdf_syntax(results_dir: Path, suite_revision: str) -> dict:
    """The RDF 1.1 and RDF 1.2 syntax ledgers, per suite (aegis-mhee08).

    RDF 1.2 is enumerated, never run: Quipu has no rdf-12 feature, and a loader
    that rejects everything would "pass" every negative case. So a 1.2 ledger
    row that claims a pass is refused, not published.
    """
    out = {}
    for version, name in (("1.1", RDF11_SYNTAX_LEDGER), ("1.2", RDF12_SYNTAX_LEDGER)):
        path = results_dir / name
        if not path.is_file():
            raise LedgerError(f"missing ledger: {path}")
        ledger = json.loads(path.read_text())
        if ledger.get("suite_revision") != suite_revision:
            raise LedgerError(f"{path} ran at rdf-tests {str(ledger.get('suite_revision'))[:8]}, "
                              f"not {suite_revision[:8]}")
        if version == "1.2" and any(row.get("passed") for row in ledger.get("results", [])):
            raise LedgerError(f"{path} scores an RDF 1.2 case as passed, but Quipu has no RDF 1.2 "
                              "support; a rejected negative case is not a pass")
        suites = ledger.get("totals", {}).get("suites", {})
        missing = [key for key, _ in RDF_SYNTAX_SUITES if key not in suites]
        if missing:
            raise LedgerError(f"{path} lacks suite(s) {missing}")
        out[version] = {"suites": suites, "reason": ledger.get("reason", "")}
    return out


def load(results_dir: Path, competitors_dir: Path | None = None) -> dict:
    """Normalise both ledger shapes into one per-class view."""
    syntax_path = results_dir / SYNTAX_LEDGER
    evaluation_path = results_dir / EVALUATION_LEDGER
    entailment_path = results_dir / ENTAILMENT_LEDGER
    shacl_path = results_dir / SHACL_LEDGER
    federated_path = results_dir / FEDERATED_LEDGER
    for path in (syntax_path, evaluation_path, entailment_path, shacl_path, federated_path):
        if not path.is_file():
            raise LedgerError(f"missing ledger: {path}")

    syntax = json.loads(syntax_path.read_text())
    evaluation = json.loads(evaluation_path.read_text())
    entailment = json.loads(entailment_path.read_text())
    shacl = json.loads(shacl_path.read_text())
    federated = json.loads(federated_path.read_text())

    classes: dict[str, dict] = {}

    # The syntax runner records pass/fail booleans rather than a status string.
    syntax_rows = [
        {
            "class": "syntax",
            "id": row["test"],
            "name": row["test"],
            "manifest": "syntax-query/manifest.ttl",
            "status": "passed" if row.get("passed") else "failed",
            "diagnostic": row.get("diagnostic", ""),
        }
        for row in syntax.get("results", [])
    ]
    if not syntax_rows:
        raise LedgerError(f"{syntax_path} carries no result rows")
    classes["syntax"] = {"rows": syntax_rows, "counts": tally(syntax_rows)}

    evaluation_rows = evaluation.get("results", [])
    if not evaluation_rows:
        raise LedgerError(f"{evaluation_path} carries no result rows")
    for name in evaluation.get("classes", {}):
        rows = [row for row in evaluation_rows if row.get("class") == name]
        classes[name] = {"rows": rows, "counts": tally(rows)}
    entailment_rows = entailment.get("results", [])
    if len(entailment_rows) != 70:
        raise LedgerError(f"{entailment_path} must carry exactly 70 result rows")
    classes["entailment"] = {"rows": entailment_rows, "counts": tally(entailment_rows)}
    federated_rows = federated.get("results", [])
    if len(federated_rows) != 7:
        raise LedgerError(f"{federated_path} must carry exactly 7 result rows")
    classes["federated-query"] = {"rows": federated_rows, "counts": tally(federated_rows)}

    unknown = set(classes) - set(CLASS_ORDER)
    if unknown:
        # A new class appearing in the ledger must be placed deliberately in
        # CLASS_ORDER, not silently appended where nobody will look at it.
        raise LedgerError(
            f"ledger carries unplaced class(es) {sorted(unknown)}; add them to CLASS_ORDER"
        )

    return {
        "classes": classes,
        "suite_revision": evaluation["suite_revision"],
        "quipu_revision": evaluation["quipu_revision"],
        "quipu_version": evaluation["quipu_version"].splitlines()[0],
        "syntax_quipu_revision": syntax["quipu_revision"],
        "isolation": evaluation.get("isolation", ""),
        "reproduce": evaluation.get("reproduce", {}),
        "entailment": entailment,
        "shacl": shacl,
        "rdf_syntax": load_rdf_syntax(results_dir, evaluation["suite_revision"]),
        "competitors": (
            load_competitors(competitors_dir, evaluation["suite_revision"])
            if competitors_dir is not None else []
        ),
    }


def badge_color(counts: dict[str, int]) -> str:
    """Colour from the honest ratio: passed over EVERY approved case."""
    if counts["cases"] == 0:
        return "lightgrey"
    if counts["executable"] == 0:
        # Nothing in the class can even run yet. "0/34" in grey says "not
        # implemented"; the same number in red would imply we tried and failed.
        return "lightgrey"
    ratio = counts["passed"] / counts["cases"]
    if ratio >= 1.0:
        return "brightgreen"
    if ratio >= 0.8:
        return "yellow"
    if ratio >= 0.5:
        return "orange"
    return "red"


def badge(name: str, counts: dict[str, int]) -> dict:
    return {
        "schemaVersion": 1,
        "label": f"SPARQL 1.1 {CLASS_LABELS[name]}",
        "message": f"{counts['passed']}/{counts['cases']}",
        "color": badge_color(counts),
    }


def _table(header: list[str], rows: list[list[str]], right: set[int] | None = None) -> list[str]:
    """Numeric columns are right-aligned; everything else reads as prose."""
    right = right or set()
    sep = ["---:" if index in right else "---" for index in range(len(header))]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(sep) + "|"]
    lines += ["| " + " | ".join(cells) + " |" for cells in rows]
    return lines


#: The classes a "passes every approved test" claim is about. Entailment and
#: federated query are NOT in it: they carry declared non-goals and a policy
#: deviation, and are named as exceptions instead (aegis-zmln5e).
#: Tests the pinned suite's manifests LIST per class, approved or not, counted
#: by parsing them as RDF (rdflib), so the page can say what the scored subset
#: is a subset of. Query evaluation: 168 Approved, 17 Proposed, 40 unclassified.
LISTED = {"query-evaluation": 225, "update": 94}

CORE_CLAIM_CLASSES = ("syntax", "query-evaluation", "update", "protocol", "result-format")


def claim_boundary(data: dict) -> list[str]:
    """The claim-boundary block, DERIVED from the ledgers (aegis-zmln5e).

    The old text said "Quipu is not a conformant SPARQL 1.1 implementation"
    beside 100% on every core class: true of the whole spec, and it
    undersold what the ledgers show. The strong sentence ("passes all
    approved ...") is emitted ONLY while every core class is fully passing; the
    moment one is not, the page falls back to per-class counts with no "all",
    so the claim cannot outlive the numbers that justify it. Exceptions are
    counted from the rows, not hand-written.
    """
    classes = data["classes"]
    core = {name: classes[name]["counts"] for name in CORE_CLAIM_CLASSES}
    all_pass = all(c["cases"] and c["passed"] == c["cases"] for c in core.values())
    counts = ", ".join(
        f"{CLASS_LABELS.get(name, name)} **{c['passed']}/{c['cases']}**" for name, c in core.items()
    )
    rev = data["suite_revision"][:7]
    if all_pass:
        head = [
            "> Quipu passes **all** Working Group–approved W3C SPARQL 1.1 Query, Update,",
            f"> Protocol and Results tests at rdf-tests `{rev}`: {counts}.",
        ]
    else:
        head = [
            "> Quipu does **not** pass every approved W3C SPARQL 1.1 Query, Update, Protocol",
            f"> and Results test at rdf-tests `{rev}`: {counts}.",
        ]
    fed = classes["federated-query"]["counts"]
    ent = classes["entailment"]["counts"]
    return [
        "> **Claim boundary — read this before quoting any number on this page.**",
        *head,
        "> Exceptions, each named below: federated query (`SERVICE`) passes"
        f" {fed['passed']}/{fed['cases']}, with {fed['unsupported']} refused by policy (variable",
        "> endpoints); entailment regimes are scored separately"
        f" ({ent['passed']}/{ent['cases']} passed, {ent['failed']} failing,"
        f" {ent['unsupported']} declared non-goals);",
        "> SHACL-SPARQL, OWL, RIF and D entailment are declared non-goals.",
        "> **What these counts are.** Working Group–approved tests only. The query-evaluation",
        f"> manifests list {LISTED['query-evaluation']} tests, and the {core['query-evaluation']['cases']} approved ones are scored;"
        f" the {LISTED['query-evaluation'] - core['query-evaluation']['cases']} Proposed or unclassified are not run.",
        "> The update-syntax suites are not run yet.",
        "> **The SPARQL 1.0 suite is not run.** These manifests hold what SPARQL 1.1 added; the",
        "> SPARQL 1.0 tests (rdf-tests `sparql/sparql10`) also bear on SPARQL 1.1 Query conformance,",
        "> and this harness does not score them yet. A trial run found real failures there, including",
        "> `sameTerm` inside `FILTER`, so read the counts above as the 1.1 additions only (aegis-soqv1r).",
        "> **This score is fitted to this suite.** Quipu's failures here were found by running this suite",
        "> and fixed against it, case by case, so a perfect score is partly a record of that work rather",
        "> than an independent sample. Other stores measured with the same harness were not tuned to it.",
        "> Every class below is scored separately and is never combined into a single",
        "> compliance percentage, because a blended figure would hide exactly the classes",
        "> that are not implemented at all.",
    ]


def render_competitors(data: dict) -> list[str]:
    """Other stores on the same harness, at the same suite revision."""
    competitors = data.get("competitors") or []
    if not competitors:
        return []
    classes = data["classes"]

    def score(counts: dict) -> str:
        return f"{counts['passed']}/{counts['cases']}"

    rows = [[
        "quipu", f"`{data['quipu_version']}`",
        score(classes["query-evaluation"]["counts"]), "—", score(classes["update"]["counts"]),
    ]]
    for system in competitors:
        query, update = system["classes"]["query-evaluation"], system["classes"]["update"]
        rows.append([
            system["label"], f"`{system['version']}`",
            score(query), str(query["lexical_form_only"]), score(update),
        ])
    out = [
        "## Other stores, same harness",
        "",
        "The same discovery, test selection and result comparison, run against other",
        f"stores at the same rdf-tests revision (`{data['suite_revision'][:8]}`). Scores use RDF",
        "term equality, the rule quipu is held to. \"Same value\" counts failures whose answer",
        "had the right values in a different lexical form; they stay failures and are",
        "shown separately, so a design choice is not presented as a wrong answer.",
        "",
    ]
    out += _table(
        ["System", "Version", "Query evaluation", "Of those failures, same value", "Update"],
        rows,
        right={2, 3, 4},
    )
    out += [
        "",
        "The quipu row is this page's own ledger. Quipu's runner compares exact labels and has",
        "no same-value tag, so that cell is empty rather than zero.",
        "",
        "**Disclosure.** Quipu parses SPARQL with `spargebra` and models RDF with `oxrdf`, both",
        "from the Oxigraph project. Where the two agree, part of that agreement is shared code.",
        "",
        "**Quipu's score is fitted to this suite.** Its failures were found by running this",
        "suite and fixed against it, case by case. The other stores were not tuned to this",
        "harness.",
        "",
        "Pinned versions, the fairness rules, every competitor deviation checked by hand, and",
        "the per-case ledgers are in",
        "[`benchmark/competitors`](https://github.com/scbrown/quipu/tree/main/benchmark/competitors).",
        "",
    ]
    return out


def render_rdf_syntax(data: dict) -> list[str]:
    """RDF 1.1 syntax scores, and RDF 1.2 as measured-not-supported (aegis-mhee08)."""
    syntax = data["rdf_syntax"]
    rows = []
    for key, label in RDF_SYNTAX_SUITES:
        one = syntax["1.1"]["suites"][key]
        two = syntax["1.2"]["suites"][key]
        rdf11 = f"{one['passed']}/{one['cases']}"
        if one.get("unsupported"):
            rdf11 += f" ({one['unsupported']} unsupported)"
        rows.append([label, rdf11, f"not supported (0/{two['cases']})"])
    out = [
        "## RDF syntax",
        "",
        "The W3C RDF 1.1 and RDF 1.2 syntax suites at the same rdf-tests revision",
        f"(`{data['suite_revision'][:8]}`). Every manifest case is counted, including cases",
        "the manifests have not marked approved.",
        "",
    ]
    out += _table(["Format", "RDF 1.1", "RDF 1.2"], rows, right={1, 2})
    out += [
        "",
        "**RDF 1.2 is measured and not supported.** Quipu is built without RDF 1.2, so it",
        "cannot parse a triple term. The RDF 1.2 cases are enumerated from the pinned",
        "manifests and not run: a loader that rejects all RDF 1.2 input would \"pass\" every",
        "negative-syntax case, and those passes would read as partial support. No RDF 1.2",
        "case is scored as a pass until the support exists.",
        "",
        "### Known deviation: literal lexical identity",
        "",
        "The current loader canonicalizes integer and double literals: for example,",
        "`\"01\"^^xsd:integer` is stored and exported as `\"1\"^^xsd:integer`.",
        "It also converts an ill-typed boolean such as `\"z\"^^xsd:boolean` to `false`,",
        "and rejects some ill-typed numeric literals during loading. These are known",
        "deviations, not the intended storage contract; affected cases remain failures.",
        "",
        "The chosen contract is to preserve lexical form and datatype as RDF term",
        "identity, including ill-typed literals, and derive numeric values separately.",
        "Distinct terms such as `\"01\"` and `\"1\"` with the same integer datatype must",
        "coexist even though their numeric values compare equal. This follows",
        "[RDF 1.1 literal term equality](https://www.w3.org/TR/rdf11-concepts/#section-Graph-Literal).",
        "An expression's effective boolean value must not replace the stored term.",
        "",
        "The preservation fix is not implemented yet. Existing data cannot recover",
        "discarded spellings; a future compatibility plan must preserve legacy term",
        "identity, exact retraction and history without inventing missing lexical forms.",
        "",
        "Ledgers: [`rdf11-syntax.json`](https://github.com/scbrown/quipu/blob/main/benchmark/public/results/rdf11-syntax.json)",
        "and [`rdf12-syntax.json`](https://github.com/scbrown/quipu/blob/main/benchmark/public/results/rdf12-syntax.json).",
        "",
    ]
    return out


def render_markdown(data: dict) -> str:
    classes = data["classes"]
    out: list[str] = [GENERATED_HEADER, "# SPARQL 1.1 conformance", ""]

    out += claim_boundary(data)
    out += [
        "",
        "These results come from the [W3C RDF Tests](https://github.com/w3c/rdf-tests)",
        "suite at a pinned revision, run against throwaway stores by a checked-in runner.",
        "You can re-derive every number on this page yourself — the commands are below.",
        "",
        "For what Quipu does with a graph once it is correct — handing it to another",
        "store, and composing another store's without trusting it — see",
        "[Sharing & Federation](../sharing/README.md). That page states its own claim",
        "boundary for `SERVICE`, including the configured-endpoint policy deviation scored below.",
        "",
        "## What was measured",
        "",
    ]
    out += _table(
        ["Field", "Value"],
        [
            ["W3C RDF Tests revision", f"`{data['suite_revision']}`"],
            ["Quipu revision (evaluation)", f"`{data['quipu_revision']}`"],
            ["Quipu revision (syntax)", f"`{data['syntax_quipu_revision']}`"],
            ["Quipu version", f"`{data['quipu_version']}`"],
            ["Store isolation", data["isolation"] or "one temporary store per test"],
            ["Test selection", "Working Group–approved tests only"],
        ],
    )
    out += [
        "",
        "## Results by class",
        "",
        "`unsupported` means the harness cannot execute the test at all — the capability",
        "is missing, not merely wrong. Those cases stay in the denominator and each one",
        "carries a named reason further down this page.",
        "",
    ]
    rows = []
    for name in CLASS_ORDER:
        counts = classes[name]["counts"]
        rows.append(
            [
                CLASS_LABELS[name],
                str(counts["passed"]),
                str(counts["failed"]),
                str(counts["error"]),
                str(counts["unsupported"]),
                str(counts["cases"]),
            ]
        )
    totals = {
        key: sum(classes[name]["counts"][key] for name in CLASS_ORDER)
        for key in ("passed", "failed", "error", "unsupported", "cases")
    }
    rows.append(
        [
            "**all classes**",
            f"**{totals['passed']}**",
            f"**{totals['failed']}**",
            f"**{totals['error']}**",
            f"**{totals['unsupported']}**",
            f"**{totals['cases']}**",
        ]
    )
    out += _table(
        ["Class", "Passed", "Failed", "Error", "Unsupported", "Approved cases"],
        rows,
        right={1, 2, 3, 4, 5},
    )
    out += [
        "",
        "The final row is an arithmetic total, not a score. It is here so the class rows",
        "can be checked against the ledgers, not so it can be quoted as a percentage.",
        "",
    ]
    out += render_competitors(data)
    out += render_rdf_syntax(data)
    out += [
        "## Query evaluation, by feature family",
        "",
        "The family is the pinned suite's own directory for each manifest, so this",
        "grouping is re-derivable by anyone holding the same suite revision. It is the",
        "map of where the work is: the largest failing families are where conformance",
        "moves the most per fix.",
        "",
    ]

    families: dict[str, list[dict]] = {}
    for row in classes["query-evaluation"]["rows"]:
        families.setdefault(family_of(row), []).append(row)
    ordered_families = sorted(
        families, key=lambda name: (-len(families[name]), name)
    )
    family_rows = []
    for name in ordered_families:
        counts = tally(families[name])
        family_rows.append(
            [
                f"`{name}`",
                str(counts["passed"]),
                str(counts["failed"]),
                str(counts["error"]),
                str(counts["unsupported"]),
                str(counts["cases"]),
            ]
        )
    out += _table(
        ["Family", "Passed", "Failed", "Error", "Unsupported", "Cases"],
        family_rows,
        right={1, 2, 3, 4, 5},
    )
    out += ["", "### The not-yet-passing tests, named", ""]
    out += [
        "Every test that does not pass is listed here with its W3C identifier, so a",
        "claim of progress can be checked against a specific case rather than a count.",
        "",
    ]
    for name in ordered_families:
        outstanding = [
            row for row in families[name] if row.get("status") not in PASS_STATUSES
        ]
        if not outstanding:
            continue
