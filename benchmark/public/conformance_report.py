#!/usr/bin/env python3
"""Render the public conformance page and badge endpoints from the pinned ledgers.

The ledgers under ``benchmark/public/results/`` are the only source of truth.
Nothing here re-scores anything: this turns a measured ledger into the two
artifacts a stranger actually reads — a page they can re-derive, and a badge
that cannot flatter us, because both are recomputed from the same JSON.

``--check`` re-renders into memory and compares against what is committed. CI
runs it so the published page cannot drift away from the ledger it claims to
report; a page that says 18/168 while the ledger says 12/168 is worse than no
page at all.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

# Ledger file -> (badge slug, human label, the class keys it carries).
# The syntax ledger predates the multi-class evaluation runner and has its own
# shape ("totals", not "classes"); it is normalised into the same view below.
SYNTAX_LEDGER = "sparql11-syntax.json"
EVALUATION_LEDGER = "sparql11-evaluation.json"
ENTAILMENT_LEDGER = "sparql11-entailment.json"
SHACL_LEDGER = "shacl-core.json"
FEDERATED_LEDGER = "sparql11-federated-query.json"

CLASS_LABELS = {
    "syntax": "query syntax",
    "query-evaluation": "query evaluation",
    "protocol": "protocol",
    "update": "update",
    "entailment": "entailment",
    "result-format": "result format",
    "federated-query": "federated query (`SERVICE`)",
}

# Order the page and the badge set. Syntax first because it is the one class
# that passes in full, and burying it would be as dishonest as leading with it
# and calling it "SPARQL 1.1 conformance".
CLASS_ORDER = [
    "syntax",
    "query-evaluation",
    "federated-query",
    "result-format",
    "protocol",
    "update",
    "entailment",
]

PASS_STATUSES = frozenset({"passed"})
# A test that the harness cannot execute is not a pass and not a failure. It is
# counted, named, and given a reason -- never quietly dropped from the
# denominator, which is the usual way a conformance number gets inflated.
UNSUPPORTED_STATUSES = frozenset({"unsupported"})

GENERATED_HEADER = (
    "<!-- Generated by benchmark/public/conformance_report.py from\n"
    "     benchmark/public/results/*.json. Do not edit by hand: `just conformance-check`\n"
    "     (and CI) will fail if this file and the ledgers disagree. -->\n"
)


class LedgerError(RuntimeError):
    """The ledgers on disk are missing or do not have the expected shape."""


def reason_of(row: dict) -> str:
    """Unsupported rows carry ``reason``; executed rows carry ``diagnostic``."""
    return (row.get("reason") or row.get("diagnostic") or "").strip()


def family_of(row: dict) -> str:
    """Feature family = the pinned suite's own directory for the manifest.

    Deriving the grouping from the W3C layout rather than inventing one keeps
    the classification re-derivable by anyone holding the same suite revision,
    and keeps it stable when we fix tests.
    """
    manifest = row.get("manifest", "")
    return manifest.rsplit("/", 1)[0] if "/" in manifest else "(root)"


def tally(rows: list[dict]) -> dict[str, int]:
    counts = {"passed": 0, "failed": 0, "error": 0, "unsupported": 0}
    for row in rows:
        status = row.get("status", "")
        if status not in counts:
            raise LedgerError(f"unknown status {status!r} in ledger row {row.get('id')!r}")
        counts[status] += 1
    counts["cases"] = len(rows)
    counts["executable"] = counts["cases"] - counts["unsupported"]
    return counts


def load(results_dir: Path) -> dict:
    """Normalise both ledger shapes into one per-class view."""
    syntax_path = results_dir / SYNTAX_LEDGER
    evaluation_path = results_dir / EVALUATION_LEDGER
    entailment_path = results_dir / ENTAILMENT_LEDGER
    shacl_path = results_dir / SHACL_LEDGER
    federated_path = results_dir / FEDERATED_LEDGER
    for path in (syntax_path, evaluation_path, entailment_path, shacl_path, federated_path):
        if not path.is_file():
            raise LedgerError(f"missing ledger: {path}")

    syntax = json.loads(syntax_path.read_text())
    evaluation = json.loads(evaluation_path.read_text())
    entailment = json.loads(entailment_path.read_text())
    shacl = json.loads(shacl_path.read_text())
    federated = json.loads(federated_path.read_text())

    classes: dict[str, dict] = {}

    # The syntax runner records pass/fail booleans rather than a status string.
    syntax_rows = [
        {
            "class": "syntax",
            "id": row["test"],
            "name": row["test"],
            "manifest": "syntax-query/manifest.ttl",
            "status": "passed" if row.get("passed") else "failed",
            "diagnostic": row.get("diagnostic", ""),
        }
        for row in syntax.get("results", [])
    ]
    if not syntax_rows:
        raise LedgerError(f"{syntax_path} carries no result rows")
    classes["syntax"] = {"rows": syntax_rows, "counts": tally(syntax_rows)}

    evaluation_rows = evaluation.get("results", [])
    if not evaluation_rows:
        raise LedgerError(f"{evaluation_path} carries no result rows")
    for name in evaluation.get("classes", {}):
        rows = [row for row in evaluation_rows if row.get("class") == name]
        classes[name] = {"rows": rows, "counts": tally(rows)}
    entailment_rows = entailment.get("results", [])
    if len(entailment_rows) != 70:
        raise LedgerError(f"{entailment_path} must carry exactly 70 result rows")
    classes["entailment"] = {"rows": entailment_rows, "counts": tally(entailment_rows)}
    federated_rows = federated.get("results", [])
    if len(federated_rows) != 7:
        raise LedgerError(f"{federated_path} must carry exactly 7 result rows")
    classes["federated-query"] = {"rows": federated_rows, "counts": tally(federated_rows)}

    unknown = set(classes) - set(CLASS_ORDER)
    if unknown:
        # A new class appearing in the ledger must be placed deliberately in
        # CLASS_ORDER, not silently appended where nobody will look at it.
        raise LedgerError(
            f"ledger carries unplaced class(es) {sorted(unknown)}; add them to CLASS_ORDER"
        )

    return {
        "classes": classes,
        "suite_revision": evaluation["suite_revision"],
        "quipu_revision": evaluation["quipu_revision"],
        "quipu_version": evaluation["quipu_version"],
        "syntax_quipu_revision": syntax["quipu_revision"],
        "isolation": evaluation.get("isolation", ""),
        "reproduce": evaluation.get("reproduce", {}),
        "entailment": entailment,
        "shacl": shacl,
    }


def badge_color(counts: dict[str, int]) -> str:
    """Colour from the honest ratio: passed over EVERY approved case."""
    if counts["cases"] == 0:
        return "lightgrey"
    if counts["executable"] == 0:
        # Nothing in the class can even run yet. "0/34" in grey says "not
        # implemented"; the same number in red would imply we tried and failed.
        return "lightgrey"
    ratio = counts["passed"] / counts["cases"]
    if ratio >= 1.0:
        return "brightgreen"
    if ratio >= 0.8:
        return "yellow"
    if ratio >= 0.5:
        return "orange"
    return "red"


def badge(name: str, counts: dict[str, int]) -> dict:
    return {
        "schemaVersion": 1,
        "label": f"SPARQL 1.1 {CLASS_LABELS[name]}",
        "message": f"{counts['passed']}/{counts['cases']}",
        "color": badge_color(counts),
    }


def _table(header: list[str], rows: list[list[str]], right: set[int] | None = None) -> list[str]:
    """Numeric columns are right-aligned; everything else reads as prose."""
    right = right or set()
    sep = ["---:" if index in right else "---" for index in range(len(header))]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(sep) + "|"]
    lines += ["| " + " | ".join(cells) + " |" for cells in rows]
    return lines


def render_markdown(data: dict) -> str:
    classes = data["classes"]
    out: list[str] = [GENERATED_HEADER, "# SPARQL 1.1 conformance", ""]

    syntax = classes["syntax"]["counts"]
    evaluation = classes["query-evaluation"]["counts"]
    out += [
        "> **Claim boundary — read this before quoting any number on this page.**",
        f"> Quipu passes **{syntax['passed']}/{syntax['cases']}** approved SPARQL 1.1",
        f"> *query-syntax* tests and **{evaluation['passed']}/{evaluation['cases']}** approved",
        "> *query-evaluation* tests. **Quipu is not a conformant SPARQL 1.1 implementation.**",
        "> Every class below is scored separately and is never combined into a single",
        "> compliance percentage, because a blended figure would hide exactly the classes",
        "> that are not implemented at all.",
        "",
        "These results come from the [W3C RDF Tests](https://github.com/w3c/rdf-tests)",
        "suite at a pinned revision, run against throwaway stores by a checked-in runner.",
        "You can re-derive every number on this page yourself — the commands are below.",
        "",
        "For what Quipu does with a graph once it is correct — handing it to another",
        "store, and composing another store's without trusting it — see",
        "[Sharing & Federation](../sharing/README.md). That page states its own claim",
        "boundary for `SERVICE`, including the configured-endpoint policy deviation scored below.",
        "",
        "## What was measured",
        "",
    ]
    out += _table(
        ["Field", "Value"],
        [
            ["W3C RDF Tests revision", f"`{data['suite_revision']}`"],
            ["Quipu revision (evaluation)", f"`{data['quipu_revision']}`"],
            ["Quipu revision (syntax)", f"`{data['syntax_quipu_revision']}`"],
            ["Quipu version", f"`{data['quipu_version']}`"],
            ["Store isolation", data["isolation"] or "one temporary store per test"],
            ["Test selection", "Working Group–approved tests only"],
        ],
    )
    out += [
        "",
        "## Results by class",
        "",
        "`unsupported` means the harness cannot execute the test at all — the capability",
        "is missing, not merely wrong. Those cases stay in the denominator and each one",
        "carries a named reason further down this page.",
        "",
    ]
    rows = []
    for name in CLASS_ORDER:
        counts = classes[name]["counts"]
        rows.append(
            [
                CLASS_LABELS[name],
                str(counts["passed"]),
                str(counts["failed"]),
                str(counts["error"]),
                str(counts["unsupported"]),
                str(counts["cases"]),
            ]
        )
    totals = {
        key: sum(classes[name]["counts"][key] for name in CLASS_ORDER)
        for key in ("passed", "failed", "error", "unsupported", "cases")
    }
    rows.append(
        [
            "**all classes**",
            f"**{totals['passed']}**",
            f"**{totals['failed']}**",
            f"**{totals['error']}**",
            f"**{totals['unsupported']}**",
            f"**{totals['cases']}**",
        ]
    )
    out += _table(
        ["Class", "Passed", "Failed", "Error", "Unsupported", "Approved cases"],
        rows,
        right={1, 2, 3, 4, 5},
    )
    out += [
        "",
        "The final row is an arithmetic total, not a score. It is here so the class rows",
        "can be checked against the ledgers, not so it can be quoted as a percentage.",
        "",
        "## Query evaluation, by feature family",
        "",
        "The family is the pinned suite's own directory for each manifest, so this",
        "grouping is re-derivable by anyone holding the same suite revision. It is the",
        "map of where the work is: the largest failing families are where conformance",
        "moves the most per fix.",
        "",
    ]

    families: dict[str, list[dict]] = {}
    for row in classes["query-evaluation"]["rows"]:
        families.setdefault(family_of(row), []).append(row)
    ordered_families = sorted(
        families, key=lambda name: (-len(families[name]), name)
    )
    family_rows = []
    for name in ordered_families:
        counts = tally(families[name])
        family_rows.append(
            [
                f"`{name}`",
                str(counts["passed"]),
                str(counts["failed"]),
                str(counts["error"]),
                str(counts["unsupported"]),
                str(counts["cases"]),
            ]
        )
    out += _table(
        ["Family", "Passed", "Failed", "Error", "Unsupported", "Cases"],
        family_rows,
        right={1, 2, 3, 4, 5},
    )
    out += ["", "### The not-yet-passing tests, named", ""]
    out += [
        "Every test that does not pass is listed here with its W3C identifier, so a",
        "claim of progress can be checked against a specific case rather than a count.",
        "",
    ]
    for name in ordered_families:
        outstanding = [
            row for row in families[name] if row.get("status") not in PASS_STATUSES
        ]
        if not outstanding:
            continue
        counts = tally(families[name])
        out += [
            "<details>",
            f"<summary><code>{name}</code> — {len(outstanding)} of {counts['cases']} "
            "not passing</summary>",
            "",
        ]
        detail_rows = [
            [f"`{row['id']}`", row.get("name", ""), row["status"], _brief(reason_of(row))]
            for row in sorted(outstanding, key=lambda row: row["id"])
        ]
        out += _table(["Test", "Name", "Status", "Reason"], detail_rows)
        out += ["", "</details>", ""]

    federated = classes["federated-query"]
    out += [
        "## Federated query (`SERVICE`)", "",
        f"Quipu passes **{federated['counts']['passed']}/{federated['counts']['cases']}** approved W3C Basic Federated Query cases.",
        "`SERVICE` is a query-planned subquery path using the same declarations and labels as `RemoteProvider`; it is separate from `GraphProvider` whole-query fanout and is not open federation.",
        "The variable-endpoint case is a deliberate policy deviation because query data cannot widen the configured remote allowlist.",
        "", "| Test | Name | Status | Reason |", "|---|---|---|---|",
    ]
    for row in federated["rows"]:
        out.append(f"| `{row['id']}` | {row['name']} | {row['status']} | {_brief(reason_of(row))} |")
    out.append("")

    out += ["## Why a class is unsupported", "", "Grouped by the reason the runner recorded.", ""]
    reasons: dict[str, list[str]] = {}
    for name in CLASS_ORDER:
        for row in classes[name]["rows"]:
            if row.get("status") in UNSUPPORTED_STATUSES:
                reasons.setdefault(reason_of(row) or "(no reason recorded)", []).append(name)
    reason_rows = []
    for reason in sorted(reasons, key=lambda key: (-len(reasons[key]), key)):
        affected = sorted(set(reasons[reason]))
        reason_rows.append(
            [
                reason,
                str(len(reasons[reason])),
                ", ".join(CLASS_LABELS[name] for name in affected),
            ]
        )
    out += _table(["Missing capability", "Cases", "Classes"], reason_rows, right={1})

    out += ["", "## Re-derive these numbers", "", "```sh"]
    reproduce = data["reproduce"]
    out += [
        "git clone https://github.com/w3c/rdf-tests /tmp/rdf-tests",
        f"git -C /tmp/rdf-tests checkout {data['suite_revision']}",
        reproduce.get("build", "cargo build --release --bin quipu"),
    ]
    environment = reproduce.get("environment", {})
    for key in sorted(environment):
        out.append(f'{key}="{environment[key]}"')
    out += [
        'python3 benchmark/public/sparql11_syntax.py --suite "$SUITE/syntax-query" \\',
        '  --quipu "$QUIPU_BIN" --output /tmp/sparql11-syntax.json',
        'python3 benchmark/public/sparql11_evaluation.py --suite "$SUITE" \\',
        '  --quipu "$QUIPU_BIN" --output /tmp/sparql11-evaluation.json',
        'python3 benchmark/public/sparql11_federated.py --suite "$SUITE" \\',
        '  --quipu "$QUIPU_BIN" --output /tmp/sparql11-federated-query.json',
        "```",
        "",
        "A nonzero exit from an incomplete runner is expected while any test fails: it",
        "writes the complete ledger first, then reports that not everything passed. Use",
        "the regression gate below to tell *worse than committed* apart from *not yet",
        "perfect*.",
        "",
        "Per-class reproduction commands are embedded in the ledger itself, under",
        "`reproduce.per_class`.",
        "",
        "## The regression gate",
        "",
        "```sh",
        "python3 benchmark/public/check_regression.py \\",
        "  --baseline benchmark/public/results/sparql11-evaluation.json \\",
        "  --candidate /tmp/sparql11-evaluation.json",
        "```",
        "",
        "It exits nonzero when a class's pass count drops or when a test that passed in",
        "the committed ledger stops passing, and it names the tests. Improvements exit",
        "zero and print the tests that newly pass — a prompt to refresh the baseline.",
        "This is what runs in CI on every release, so a published number cannot silently",
        "get worse.",
        "",
        "## Full ledgers",
        "",
        "- [`benchmark/public/results/sparql11-syntax.json`]"
        "(https://github.com/scbrown/quipu/blob/main/benchmark/public/results/sparql11-syntax.json)",
        "- [`benchmark/public/results/sparql11-evaluation.json`]"
        "(https://github.com/scbrown/quipu/blob/main/benchmark/public/results/sparql11-evaluation.json)",
        "- [`benchmark/public/results/sparql11-federated-query.json`]"
        "(https://github.com/scbrown/quipu/blob/main/benchmark/public/results/sparql11-federated-query.json)",
        "",
        "Each row records its class, test identifier, manifest, query and result paths,",
        "status, and diagnostic or unsupported reason.",
        "",
    ]
    shacl_rows = data["shacl"].get("results", [])
    core_rows = [row for row in shacl_rows if row.get("category") != "shacl-sparql"]
    sparql_rows = [row for row in shacl_rows if row.get("category") == "shacl-sparql"]
    core_counts, sparql_counts = tally(core_rows), tally(sparql_rows)
    out += [
        "## W3C SHACL conformance", "",
        f"Quipu passes **{core_counts['passed']}/{core_counts['cases']}** manifest-reachable SHACL Core cases.",
        f"SHACL-SPARQL remains a deliberate non-goal: **{sparql_counts['passed']}/{sparql_counts['cases']}** pass and {sparql_counts['unsupported']} are unsupported.",
        "Quipu does not advertise SHACL-SPARQL support; the upstream SPARQL validator is incomplete, and support requires the full 22-case manifest gate rather than a partial claim.",
        "This score uses the context-free native validator; write-gate transaction behavior is tested separately.", "",
        f"Pinned W3C Data Shapes revision: `{data['shacl']['suite_revision']}`.",
        "The pinned manifest exposes 120 approved cases (98 Core + 22 SHACL-SPARQL).",
        "`nodeValidator-001.ttl` exists in the checkout but is not manifest-reachable and is not scored.", "",
        "| SHACL class | Passed | Failed | Error | Unsupported | Cases |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for category in data["shacl"].get("classes", {}):
        counts = tally([row for row in shacl_rows if row.get("category") == category])
        out.append(f"| `{category}` | {counts['passed']} | {counts['failed']} | {counts['error']} | {counts['unsupported']} | {counts['cases']} |")
    entailment = classes["entailment"]["counts"]
    # Read the commitment from the LEDGER rather than printing a literal. The
    # previous version stated "All six regimes remain deliberate non-goals" and
    # a hardcoded third column, so flipping a regime changed nothing here and
    # the page would have kept publishing the old claim over new data
    # (aegis-1gp76j).
    entailment_rows = [
        row for row in data["entailment"].get("results", [])
        if row.get("decision_bucket")
    ]
    commitments: dict[str, str] = {}
    for row in entailment_rows:
        commitments.setdefault(row["decision_bucket"], row.get("commitment", "deliberate-non-goal"))
    goals = sorted(r for r, c in commitments.items() if c == "goal")
    non_goals = sorted(r for r, c in commitments.items() if c != "goal")

    if goals:
        goal_rows = [r for r in entailment_rows if commitments.get(r["decision_bucket"]) == "goal"]
        goal_passed = sum(1 for r in goal_rows if r.get("status") == "passed")
        headline = (
            f"{len(goals)} of {len(commitments)} regimes are goals ({', '.join(goals)}): "
            f"**{goal_passed}/{len(goal_rows)}** of their cases pass. "
            f"The remaining {len(non_goals)} are deliberate non-goals."
        )
    else:
        headline = (
            f"All {len(commitments)} regimes remain deliberate non-goals: "
            f"**{entailment['passed']}/{entailment['cases']}** pass and "
            f"{entailment['unsupported']} are unsupported."
        )
    # Ledger PROVENANCE beside the headline: WHEN it was re-derived and BY WHAT.
    # A page that states only WHAT was measured cannot show that its own
    # regression gate has been dead for two days — which is exactly what
    # happened between 09-03 and 09-05 (aegis-1gp76j / aegis-tydvlg).
    led = data["entailment"]
    when = led.get("generated_at")
    by = led.get("generated_by")
    if when and by:
        origin = f"[CI run]({by})" if by.startswith("http") else f"**{by}** — NOT CI-produced"
        prov = f"Ledger re-derived {when} by {origin}, from quipu `{led['quipu_revision'][:12]}`."
    else:
        prov = (
            "Ledger carries no re-derivation provenance — it predates "
            "`generated_at`/`generated_by`, so WHEN and BY WHAT are unknown."
        )
    out += ["", "## Entailment-regime commitments", "", headline, prov,
        "Local RDFS and OWL extensions beyond a goal regime are not standards-regime claims.", "",
    ]
    if goals:
        # The caveat rides WITH the number, in the generator, because a reader
        # who sees only the fraction will size the remaining work from it and
        # size the wrong thing (aegis-1gp76j).
        out += [
            "> **Do not read the goal-regime fraction as \"nearly done\".** The two numbers have "
            "different characters. Most RDF-regime cases are `bind*` tests answerable under simple "
            "entailment, so they pass without any additional inference — a high RDF score is not "
            "evidence of an entailment engine. The RDFS score DOES reflect one: an RDFS closure "
            "(rdfs2/3/5/7/9/11) is materialised into the graph's companion inferred graph and "
            "composed into the default graph when the regime is in force, which is what a query "
            "like `SELECT ?x WHERE { ex:a ?x ex:c }` needs — its predicate is a variable, so the "
            "entailed triple has to EXIST and cannot be produced by rewriting the pattern. What "
            "remains failing is not more of the same closure: it is container and axiomatic shapes "
            "beyond those six rules, and OWL-flavoured cases filed under RDFS.",
            "",
        ]
    out += ["| Regime | Cases | Passed | Commitment |", "|---|---:|---:|---|"]
    for regime, count in data["entailment"]["classes"]["entailment"]["decision_buckets"].items():
        commitment = commitments.get(regime, "deliberate-non-goal")
        passed = sum(
            1 for r in entailment_rows
            if r.get("decision_bucket") == regime and r.get("status") == "passed"
        )
        label = "goal" if commitment == "goal" else "deliberate non-goal"
        out.append(f"| {regime} | {count} | {passed} | {label} |")
    out += ["", "Machine ledgers: [`shacl-core.json`](https://github.com/scbrown/quipu/blob/main/benchmark/public/results/shacl-core.json) and [`sparql11-entailment.json`](https://github.com/scbrown/quipu/blob/main/benchmark/public/results/sparql11-entailment.json).", ""]
    return "\n".join(out)


def _brief(text: str, limit: int = 90) -> str:
    """One-line, table-safe reason, rendered as a code span.

    Runner diagnostics quote the offending query, so they carry bare IRIs. A
    code span keeps those out of the prose linter and reads correctly as the
    machine output it is.
    """
    flat = " ".join(text.split())
    if not flat:
        return ""
    if len(flat) > limit:
        flat = flat[: limit - 1].rstrip() + "…"
    # A backtick inside the diagnostic would close the span early; the table
    # cell must survive whatever the runner emitted.
    longest = max((len(run) for run in re.findall(r"`+", flat)), default=0)
    fence = "`" * (longest + 1)
    padding = " " if flat.startswith("`") or flat.endswith("`") else ""
    return f"{fence}{padding}{flat.replace('|', '\\|')}{padding}{fence}"


def artifacts(data: dict, docs_dir: Path) -> dict[Path, str]:
    """Every file this generator owns, as path -> exact content."""
    files: dict[Path, str] = {docs_dir / "conformance.md": render_markdown(data)}
    for name in CLASS_ORDER:
        payload = badge(name, data["classes"][name]["counts"])
        files[docs_dir / "badges" / f"sparql11-{name}.json"] = (
            json.dumps(payload, indent=2, sort_keys=True) + "\n"
        )
    shacl_counts = tally([row for row in data["shacl"]["results"] if row["category"] != "shacl-sparql"])
    files[docs_dir / "badges" / "shacl-core.json"] = json.dumps({
        "schemaVersion": 1, "label": "W3C SHACL Core",
        "message": f"{shacl_counts['passed']}/{shacl_counts['cases']}",
        "color": badge_color(shacl_counts),
    }, indent=2, sort_keys=True) + "\n"
    return files


# Paths whose change can move a conformance number. A ledger derived from a
# revision that differs from HEAD only in docs or CI config still describes the
# code it ships beside; one that differs HERE does not.
#
# A git PATHSPEC, deliberately narrow. `benchmark/public` wholesale was wrong
# and self-defeating: it contains `results/*.json`, the ledgers themselves, so
# committing a freshly re-derived ledger would itself count as a code change
# and the check could never be satisfied. Measured while writing it — a guard
# that can never go green is not a guard.
CODE_PATHS = ("src", "benchmark/public/*.py")


def _git(*args: str) -> tuple[int, str]:
    proc = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        cwd=str(Path(__file__).resolve().parents[2]),
        check=False,
    )
    return proc.returncode, proc.stdout.strip()


def ledger_provenance(data: dict, pr_base: str | None = None) -> tuple[int, list[str]]:
    """Is each ledger derived from the code it ships beside?

    Returns ``(exit_code, messages)`` with THREE outcomes, because two cannot
    express the one that matters:

    * ``0`` — the ledger's revision is HEAD, or differs from it only outside
      ``CODE_PATHS``. A docs-only or ledger-only commit does not invalidate a
      measurement.
    * ``1`` — DRIFT. The ledger was produced by CI, from a genuinely different
      build of the code it ships with. This is the case `--check` could not see
      before (wu, review of #150): it compared the PAGE against the LEDGER and
      never the LEDGER against HEAD.
    * ``2`` — CANNOT VERIFY, never silently ``0``. Chiefly a SHALLOW CLONE: the
      ledger's revision is simply absent from a ``--depth=1`` checkout, and
      `git diff` then fails for a reason that has nothing to do with drift. A
      pass/fail verdict is FORCED to render "I examined nothing" as "nothing
      was wrong", which is the direction that lets drift through (aegis-9bgp).
    """
    rc, head = _git("rev-parse", "HEAD")
    if rc != 0:
        return 2, ["cannot resolve HEAD (not a git checkout?) — provenance UNVERIFIED"]

    # PR MODE (aegis-1gp76j, approved by wu 2026-09-05).
    #
    # On `main` the question is "was this published ledger derived from the code
    # it ships beside?" — a strict HEAD comparison, and the invariant now rests
    # entirely there.
    #
    # On a PR the strict form asks something else by accident. Merging main in
    # moves HEAD, so a ledger goes "stale" because SOMEBODY ELSE changed src —
    # which measures branch freshness, not provenance. Measured on #156: two
    # full re-derives in one hour, both returning entailment 29/6. Zero
    # information, ~10 minutes of CI each, once per unrelated merge.
    #
    # So in PR mode only the files THIS PR CHANGED can put its ledger out of
    # date. A PR that touches src still re-derives, always (wu's condition 3):
    # its own changed files are exactly what the ledger must cover.
    own: set[str] | None = None
    if pr_base:
        base_rc, base = _git("merge-base", pr_base, head)
        if base_rc != 0:
            return 2, [
                f"cannot resolve merge-base with {pr_base} — provenance UNVERIFIED "
                f"(fetch-depth: 0?)"
            ]
        rc_own, changed = _git("diff", "--name-only", base, head, "--", *CODE_PATHS)
        if rc_own != 0:
            return 2, ["cannot diff this PR against its base — provenance UNVERIFIED"]
        own = set(changed.splitlines())

    revisions = {
        key: value
        for key, value in data.items()
        if key.endswith("quipu_revision") and isinstance(value, str) and value
    }
    if not revisions:
        return 2, ["no quipu_revision in any ledger — provenance UNVERIFIED"]

    drifted: list[str] = []
    unknown: list[str] = []
    for key, revision in sorted(revisions.items()):
        if revision == head:
            continue
        if _git("cat-file", "-e", f"{revision}^{{commit}}")[0] != 0:
            unknown.append(
                f"{key}={revision[:8]} is not in this clone — SHALLOW? "
                f"provenance UNVERIFIED (checkout with fetch-depth: 0)"
            )
            continue
        rc, changed = _git("diff", "--name-only", revision, head, "--", *CODE_PATHS)
        if rc != 0:
            unknown.append(f"{key}={revision[:8]}: git diff failed — provenance UNVERIFIED")
            continue
        files = changed.splitlines()
        if own is not None:
            files = [f for f in files if f in own]
        if files:
            drifted.append(
                f"{key}={revision[:8]} but HEAD={head[:8]}, and "
                f"{len(files)} code file(s) differ between them: "
                + ", ".join(files[:4])
                + (" ..." if len(files) > 4 else "")
            )
    if unknown:
        return 2, unknown
    if drifted:
        return 1, drifted
    return 0, []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", type=Path, default=Path("benchmark/public/results"))
    parser.add_argument("--docs-dir", type=Path, default=Path("docs/book/src/benchmarks"))
    parser.add_argument(
        "--pr-base",
        default=os.environ.get("GITHUB_BASE_REF") or None,
        help="base ref of the PR under test; enables PR mode, where only THIS "
             "PR's own conformance-relevant changes can stale its ledger. "
             "Defaults to $GITHUB_BASE_REF, which GitHub sets on pull_request "
             "events and leaves unset on push — so main gets the strict arm "
             "with no configuration.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the committed files differ from the ledgers",
    )
    args = parser.parse_args(argv)

    try:
        data = load(args.results_dir)
    except (LedgerError, KeyError, json.JSONDecodeError) as error:
        print(f"conformance_report: {error}", file=sys.stderr)
        return 2

    files = artifacts(data, args.docs_dir)

    if args.check:
        stale = [
            path
            for path, content in sorted(files.items())
            if not path.is_file() or path.read_text() != content
        ]
        if stale:
            print(
                "conformance_report: published results disagree with the ledgers:",
                file=sys.stderr,
            )
            for path in stale:
                state = "missing" if not path.is_file() else "stale"
                print(f"  {state}: {path}", file=sys.stderr)
            print(
                "Regenerate with: python3 benchmark/public/conformance_report.py",
                file=sys.stderr,
            )
            return 1
        # Which arm ran is PRINTED, always. wu's condition on the PR-mode
        # refinement: the two arms answer different questions, so a bare
        # "provenance ok" would mean two things and a reader could not tell
        # which guarantee they were given.
        base = None
        if args.pr_base:
            base = args.pr_base if "/" in args.pr_base else f"origin/{args.pr_base}"
        arm = f"PR mode (base {base})" if base else "STRICT mode (ledger revision must be HEAD)"
        print(f"conformance_report: provenance arm = {arm}")
        code, messages = ledger_provenance(data, base)
        if code:
            label = (
                "ledger provenance CANNOT BE VERIFIED"
                if code == 2
                else "a ledger was NOT derived from the code it ships with"
            )
            print(f"conformance_report: {label}:", file=sys.stderr)
            for message in messages:
                print(f"  {message}", file=sys.stderr)
            if code == 1:
                print(
                    "Re-derive on this HEAD: gh workflow run conformance.yml --ref <branch>",
                    file=sys.stderr,
                )
            return code
        print(f"conformance_report: {len(files)} published artifact(s) match the ledgers")
        if base:
            print(
                "conformance_report: every ledger covers THIS PR's own "
                "conformance-relevant changes (main's are checked on push)"
            )
        else:
            print("conformance_report: every ledger is derived from the code it ships with")
        return 0

    for path, content in sorted(files.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
