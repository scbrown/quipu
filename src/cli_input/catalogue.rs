//! Store-free CLI syntax. Values and switches are separate so option values
//! (including a literal `--help`) are never reinterpreted as commands.

pub(super) struct Spec {
    pub path: &'static str,
    pub operands: &'static str,
    pub min: usize,
    pub max: usize,
    pub values: &'static str,
    pub switches: &'static str,
}

macro_rules! spec {
    ($path:literal, $operands:literal, $min:expr, $max:expr, $values:literal, $switches:literal) => {
        Spec {
            path: $path,
            operands: $operands,
            min: $min,
            max: $max,
            values: $values,
            switches: $switches,
        }
    };
}

// A group has no executable syntax; its children describe the operations.
const GROUP: usize = usize::MAX;
pub(super) fn is_group(spec: &Spec) -> bool {
    spec.min == GROUP
}

